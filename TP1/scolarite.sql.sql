SET NAMES utf8mb4;
DROP DATABASE IF EXISTS scolarite;
CREATE DATABASE scolarite CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE scolarite;

CREATE TABLE filiere (
  code     VARCHAR(4)   PRIMARY KEY,
  libelle  VARCHAR(80)  NOT NULL
) ENGINE=InnoDB;

CREATE TABLE etudiant (
  matricule  VARCHAR(10)  PRIMARY KEY,
  prenom     VARCHAR(40)  NOT NULL,
  nom        VARCHAR(40)  NOT NULL,
  filiere    VARCHAR(4)   NOT NULL,
  email      VARCHAR(80)  NOT NULL UNIQUE,
  FOREIGN KEY (filiere) REFERENCES filiere(code)
) ENGINE=InnoDB;

CREATE TABLE ec (
  code     VARCHAR(6)   PRIMARY KEY,
  intitule VARCHAR(80)  NOT NULL,
  credits  TINYINT      NOT NULL CHECK (credits BETWEEN 1 AND 10)
) ENGINE=InnoDB;

CREATE TABLE note (
  id         INT AUTO_INCREMENT PRIMARY KEY,
  matricule  VARCHAR(10)   NOT NULL,
  ec         VARCHAR(6)    NOT NULL,
  valeur     DECIMAL(4,2)  NOT NULL CHECK (valeur BETWEEN 0 AND 20),
  FOREIGN KEY (matricule) REFERENCES etudiant(matricule),
  FOREIGN KEY (ec)        REFERENCES ec(code),
  UNIQUE KEY un_note (matricule, ec)
) ENGINE=InnoDB;

